import { chromium } from "/Users/ajaypavan/creature-arena/node_modules/playwright-core/index.mjs";
import { serve } from "./serve.mjs";
const [W, H, OUT] = [Number(process.argv[2]), Number(process.argv[3]), process.argv[4]];
const srv = await serve("/Users/ajaypavan/creature-arena/dist");
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: W, height: H } });
const errs = []; page.on("console", (m) => m.type() === "error" && errs.push(m.text())); page.on("pageerror", (e) => errs.push(String(e)));
const reqs = []; page.on("request", (r) => reqs.push(r.url().replace(srv.url, "/")));
await page.goto(srv.url + "#rec");
await page.getByTestId("start").waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}_title.png` });
await page.getByTestId("start").click();
await page.waitForTimeout(2700);
await page.keyboard.down("KeyD"); await page.waitForTimeout(700); await page.keyboard.up("KeyD");
await page.keyboard.press("KeyF"); await page.waitForTimeout(60);
await page.screenshot({ path: `${OUT}_fight.png` });
console.log(JSON.stringify(await page.evaluate(() => { const g = globalThis.__arena(); return g.fighters.map((f) => ({ hp: f.hp, x: Math.round(f.x), y: Math.round(f.y) })); })));
console.log("errors:", errs, "\nrequests:", reqs);
await browser.close(); srv.close();
